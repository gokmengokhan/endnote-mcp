#!/usr/bin/env python3
"""Generate src/endnote_mcp/reftypes.py from EndNote's own reference type table.

Every EndNote record has the same generic fields; a reference type only gives
some of them its own labels. A Report's "Institution" is the generic
Publisher field, and a Web Page's "Access Date" is the generic Number field,
not the generic Access Date. EndNote ships these labels in RefTypeTable.xml;
this script turns them into the maps add_reference writes with.

Usage:
    python scripts/gen_reftypes.py [path/to/RefTypeTable.xml]

Then check the result against a scratch library with
scripts/verify_reftypes_live.py.
"""

from __future__ import annotations

import sys
import xml.etree.ElementTree as ET
from pathlib import Path

DEFAULT_TABLE = Path(
    "/Applications/EndNote 2025/EndNote 2025.app/Contents/Resources/"
    "ENCore.bundle/Contents/Resources/en.lproj/RefTypeTable.xml"
)
OUT = Path(__file__).resolve().parents[1] / "src" / "endnote_mcp" / "reftypes.py"

# Reference types add_reference supports, with the number EndNote gives each
# one in its XML (the table's own ids are different numbers).
SUPPORTED = {
    "Journal Article": 17,
    "Book": 6,
    "Book Section": 5,
    "Report": 27,
    "Web Page": 12,
    "Conference Proceedings": 10,
}

# Generic field -> path in EndNote's XML. Checked field by field against
# EndNote 2025 with scripts/verify_reftypes_live.py. File Attachments is
# written by add_reference's pdf_url; Figure and Custom 8 are left out.
GENERIC_XML = {
    "Author": "contributors/authors/author",
    "Secondary Author": "contributors/secondary-authors/author",
    "Tertiary Author": "contributors/tertiary-authors/author",
    "Subsidiary Author": "contributors/subsidiary-authors/author",
    "Translated Author": "contributors/translated-authors/author",
    "Author Address": "auth-address",
    "Title": "titles/title",
    "Secondary Title": "titles/secondary-title",
    "Tertiary Title": "titles/tertiary-title",
    "Alternate Title": "titles/alt-title",
    "Short Title": "titles/short-title",
    "Translated Title": "titles/translated-title",
    "Pages": "pages",
    "Volume": "volume",
    "Number": "number",
    "Number of Volumes": "num-vols",
    "Edition": "edition",
    "Section": "section",
    "Reprint Edition": "reprint-edition",
    "Keywords": "keywords/keyword",
    "Year": "dates/year",
    "Date": "dates/pub-dates/date",
    "Place Published": "pub-location",
    "Publisher": "publisher",
    "Original Publication": "orig-pub",
    "ISBN/ISSN": "isbn",
    "Accession Number": "accession-num",
    "Call Number": "call-num",
    "DOI": "electronic-resource-num",
    "Abstract": "abstract",
    "Label": "label",
    "Caption": "caption",
    "Notes": "notes",
    "Research Notes": "research-notes",
    "Type of Work": "work-type",
    "Reviewed Item": "reviewed-item",
    "Name of Database": "remote-database-name",
    "Database Provider": "remote-database-provider",
    "Language": "language",
    "URL": "urls/related-urls/url",
    "Access Date": "access-date",
    "Custom 1": "custom1",
    "Custom 2": "custom2",
    "Custom 3": "custom3",
    "Custom 4": "custom4",
    "Custom 5": "custom5",
    "Custom 6": "custom6",
    "Custom 7": "custom7",
}


def read_table(path: Path) -> dict[str, list[tuple[str, str]]]:
    """Reference type -> [(label, generic field)], in EndNote's display order."""
    root = ET.parse(path).getroot()
    types = {rt.get("name"): rt for rt in root.findall("RefType")}
    generic = {f.get("id"): f.text for f in types["Generic"].find("Fields")}
    out = {}
    for name in SUPPORTED:
        fields = sorted(types[name].find("Fields"), key=lambda f: int(f.get("order")))
        out[name] = [(f.text, generic[f.get("id")]) for f in fields]
    return out


def render(table: dict[str, list[tuple[str, str]]]) -> str:
    lines = [
        '"""Field labels of the reference types add_reference can create.',
        "",
        "GENERATED by scripts/gen_reftypes.py from EndNote's RefTypeTable.xml; do",
        "not edit by hand. Every EndNote record has the same generic fields, and a",
        "reference type only relabels some of them: a Report's \"Institution\" is the",
        "generic Publisher field, a Web Page's \"Access Date\" the generic Number field.",
        '"""',
        "",
        "# Generic EndNote field -> its path in EndNote's XML.",
        "GENERIC_XML: dict[str, str] = {",
    ]
    lines += [f"    {k!r}: {v!r}," for k, v in GENERIC_XML.items()]
    lines += [
        "}",
        "",
        "# Generic fields that hold names, one person or organisation per entry.",
        "NAME_FIELDS = frozenset({",
        "    'Author', 'Secondary Author', 'Tertiary Author', 'Subsidiary Author',",
        "    'Translated Author',",
        "})",
        "",
        "# Generic fields that take several values.",
        "LIST_FIELDS = NAME_FIELDS | {'Keywords'}",
        "",
        "# Reference type -> (its number in EndNote's XML,",
        "#                    {label EndNote shows for this type: generic field}).",
        "REF_TYPES: dict[str, tuple[int, dict[str, str]]] = {",
    ]
    for name, fields in table.items():
        lines.append(f"    {name!r}: ({SUPPORTED[name]}, {{")
        for label, gen in fields:
            if gen in GENERIC_XML:
                lines.append(f"        {label!r}: {gen!r},")
        lines.append("    }),")
    lines.append("}")
    return "\n".join(lines) + "\n"


def main() -> None:
    source = Path(sys.argv[1]) if len(sys.argv) > 1 else DEFAULT_TABLE
    OUT.write_text(render(read_table(source)), encoding="utf-8")
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
